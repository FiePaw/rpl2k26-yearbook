    /**
     * API function untuk download Spotify
     * Menerima input object dan mengembalikan hasil
     */
    async downloadSpotifyAPI(req) {
        const { spotifyUrl, outputDir = "profile_music", cookieFile = null } = req;
        
        // Validasi input
        if (!spotifyUrl) {
            return {
                success: false,
                error: "URL Spotify harus disediakan"
            };
        }

        try {
            // Set output directory
            this.outputDir = outputDir;
            
            // Check apakah playlist atau single track
            if (spotifyUrl.includes('/playlist/')) {
                return await this.downloadPlaylist(spotifyUrl, cookieFile);
            } else {
                return await this.downloadTrack(spotifyUrl, cookieFile);
            }
        } catch (error) {
            return {
                success: false,
                error: error.message
            };
        }
    }
